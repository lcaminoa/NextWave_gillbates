MAX_MODEL_TURNS = 10
MAX_REPORT_ATTEMPTS = 2


class AgentClaimDraft(BaseModel):
    """Strict claim shape generated by Structured Outputs."""

    model_config = ConfigDict(extra="forbid")

    claim: str = Field(min_length=1)
    evidence_ids: list[str] = Field(min_length=1)
    confidence: float = Field(ge=0, le=1)


class AgentReportDraft(BaseModel):
    """Only fields the model may decide; trusted fields are added by the application."""

    model_config = ConfigDict(extra="forbid")

    status: ReportStatus
    winning_candidate_id: str | None
    summary: str = Field(min_length=1)
    claims: list[AgentClaimDraft]
    recommended_action: str = Field(min_length=1)


